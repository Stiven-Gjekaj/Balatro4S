typedef struct {
    uint8_t field;
    double number;
    const char *text;
} BOConfigValue;

typedef struct {
    const char *key;
    const char *name;
    uint8_t set;
    int16_t order;
    uint8_t rarity;
    int8_t cost;
    int8_t pos_x, pos_y;
    int8_t soul_x, soul_y;     // -1 when the card has no second layer.
    uint8_t unlocked;
    uint8_t blueprint_compat;
    uint8_t eternal_compat;
    uint8_t perishable_compat;
    int16_t min_ante;          // For a tag.
    uint8_t consumeable;
    uint8_t hidden;            // The Soul and Black Hole: not in the normal pools.
    uint8_t omit;              // Not in any pool.
    double weight;             // The weight of a booster pack in get_pack.
    const char *kind;          // The kind of a booster pack, as "Arcana".
    const char *effect;
    const char *enhancement_gate;
    const char *no_pool_flag;
    const char *yes_pool_flag;
    const char *hand_type;     // config.type, as "Pair".
    double mult, h_mult, h_x_mult, h_dollars, p_dollars, t_mult, t_chips, x_mult, h_size, d_size, bonus;
    double extra;              // config.extra when it is a number.
    uint8_t config_count;
    const BOConfigValue *config;
    // unlock_condition: its type, as "win_deck", or NULL; its number (extra,
    // amount, count, stake, ante, chips, or n_rounds); its text (extra,
    // deck, suit, or the key of an enhancement); and its kind: 1 for
    // tarot_count or a suit, 2 for planet_count or an enhancement, 3 for a
    // tally of all enhancements.
    const char *unlock_type;
    double unlock_number;
    const char *unlock_text;
    uint8_t unlock_kind;
    uint8_t discovered;        // The card is in the collection of a new profile.
} BOCenterInfo;

